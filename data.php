// Helper functions for cart
if (session_status() === PHP_SESSION_NONE) {
    session_start();
}
if (!isset($_SESSION['cart'])) {
    $_SESSION['cart'] = [];
}

function addToCart($id, $type, $custom_price = null, $custom_notes = null) {
    global $cats, $programs;
    
    $item_id = $id;
    if ($type === 'program' && ($custom_price !== null || $custom_notes !== null)) {
        // uniquely identify custom scoped program in cart
        $item_id = $id . '_' . uniqid();
    }
    
    if (isset($_SESSION['cart'][$item_id]) && $type === 'cat') {
        $_SESSION['cart'][$item_id]['qty']++;
        return;
    }
    
    if ($type === 'cat' && isset($cats[$id])) {
        $p = $cats[$id];
        $_SESSION['cart'][$item_id] = [
            'id' => $id,
            'name' => $p['name'],
            'type' => 'cat',
            'price' => $p['price'],
            'qty' => 1,
            'details' => ''
        ];
    } elseif ($type === 'program' && isset($programs[$id])) {
        $p = $programs[$id];
        $_SESSION['cart'][$item_id] = [
            'id' => $id,
            'name' => $p['name'],
            'type' => 'program',
            'price' => $custom_price ?? $p['price'],
            'qty' => 1,
            'details' => $custom_notes ?? 'ขนาดขอบเขตมาตรฐาน'
        ];
    }
}

function getCartCount() {
    $count = 0;
    if (isset($_SESSION['cart'])) {
        foreach ($_SESSION['cart'] as $item) {
            $count += $item['qty'];
        }
    }
    return $count;
}

function getCartTotal() {
    $total = 0;
    if (isset($_SESSION['cart'])) {
        foreach ($_SESSION['cart'] as $item) {
            $total += $item['price'] * $item['qty'];
        }
    }
    return $total;
}
